
a = int( input( "Enter value of A : "))
o = input( "Enter Operator: ")
b = int( input( "Enter value of B : "))

if o == "+":
    print("Result :", a + b)
elif o == "-":
    print("Result :", a - b)
elif o == "*":
    print("Result :", a * b)
elif o == "/":
    print("Result :", a / b)
elif o == "//":
    print("Result :", a // b)
elif o == "**":
    print("Result :", a ** b)