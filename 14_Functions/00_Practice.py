# Q8: Write a program to define and call a function that returns the factorial of a number.

def factorial(num:int):
    if num == 0: print("Factorial is not defined for negative numbers.")

    result = 1
    for i in range(1, num + 1):
        result *= i

    print(result)

factorial(6)

